# ============================================================================ query encoding
def bstr(cells):
    """canonical boulder string, identical to the Lua side (string sort of 'x.y')."""
    return ':'.join(sorted(f'{x}.{y}' for x, y in cells))


def check_query(g, qid, h, B, keys):
    """deterministic check query: [qid, sx, sy, keys, boulders, hero trace, {i: boulder str}, b0 str]"""
    tr = g.det_walk(h, B, keys)
    assert tr is not None
    ex, eb = [], {}
    prevB = B
    for i, (h2, B2) in enumerate(tr, 1):
        ex += list(g.cl[h2])
        if B2 != prevB:
            eb[i] = bstr(g.bset(B2))
            prevB = B2
    x, y = g.cl[h]
    return [qid, x, y, keys, [list(c) for c in g.bset(B)], ex, eb, bstr(g.bset(B))]


def trace_query(g, qid, h, B, keys):
    x, y = g.cl[h]
    return [qid, x, y, keys, [list(c) for c in g.bset(B)], None, None, bstr(g.bset(B))]


class Jobs:
    def __init__(self, phase):
        self.phase = phase
        self.jobs = []
        self.meta = {}
        self.qid = 0

    def add(self, gname, g, queries, mode='C', batch=300, label=''):
        for i in range(0, len(queries), batch):
            self.jobs.append(dict(gadget=gname, label=label, mode=mode, spec=g.spec(), queries=queries[i:i + batch]))

    def next(self):
        self.qid += 1
        return self.qid

    def save(self):
        p = os.path.join(OUT, f'jobs_{self.phase}.json')
        json.dump(dict(phase=self.phase, jobs=self.jobs, meta=self.meta), open(p, 'w'))
        nq = sum(len(j['queries']) for j in self.jobs)
        nk = sum(len(q[3]) for j in self.jobs for q in j['queries'])
        log(f'wrote {p}: {len(self.jobs)} jobs, {nq} queries, {nk} keys')


def windows_for(g):
    """tiling of a big map into <= WMAX x HMAX windows; every cell lies >= 4 from the cut edges of some window."""
    if g.fits():
        return [(0, 0, g.W - 1, g.H - 1)]
    out = []

    def starts(n, w):
        if n <= w:
            return [0]
        s = list(range(0, n - w, w - 8))
        if s[-1] != n - w:
            s.append(n - w)
        return s
    ww, hh = min(g.W, WMAX), min(g.H, HMAX)
    for y0 in starts(g.H, hh):
        for x0 in starts(g.W, ww):
            out.append((x0, y0, x0 + ww - 1, y0 + hh - 1))
    return out


def home_window(c, wins, g):
    x, y = c
    for (x0, y0, x1, y1) in wins:
        okx = (x - x0 >= 4 or x0 == 0) and (x1 - x >= 4 or x1 == g.W - 1)
        oky = (y - y0 >= 4 or y0 == 0) and (y1 - y >= 4 or y1 == g.H - 1)
        if x0 <= x <= x1 and y0 <= y <= y1 and okx and oky:
            return (x0, y0, x1, y1)
    raise AssertionError(('no window', c))


# ============================================================================ phase: neigh
READ = [(dx, dy) for dx, dy in KEYS.values()] + [(2 * dx, 2 * dy) for dx, dy in D4]


def gen_neigh(names, contexts=2, maxpat=4096):
    G = gadgets()
    J = Jobs('neigh')
    rng = random.Random(SEED)
    seen = {}              # (terrain 5x5, pattern) -> number of contexts queued
    per = {}
    for name in names:
        g = G[name]
        dyn = g.dyn()
        wins = windows_for(g)
        byw = {}
        uniq = dup = skipped = 0
        for h in sorted(g.cells):
            if h in g.traps:
                continue
            if g.traps and h in {c for t in g.traps for c in g.landing[t]}:
                skipped += 1            # hero cells A, B inside the coin zone Z are tested by the seq/walk phases
                continue
            terr = ''.join(('X' if (h[0] + dx, h[1] + dy) not in g.cells else g.cells[(h[0] + dx, h[1] + dy)])
                           + ('d' if (h[0] + dx, h[1] + dy) in dyn else '')
                           for dy in range(-2, 3) for dx in range(-2, 3))
            rd = [(h[0] + dx, h[1] + dy) for dx, dy in READ if (h[0] + dx, h[1] + dy) in dyn]
            ring = [c for c in dyn if c != h and c not in rd and max(abs(c[0] - h[0]), abs(c[1] - h[1])) <= 4]
            n = len(rd)
            assert 2 ** n <= maxpat, (name, h, n)
            w = home_window(h, wins, g)
            for m in range(2 ** n):
                pat = [rd[i] for i in range(n) if m >> i & 1]
                key = (terr, tuple(sorted((c[0] - h[0], c[1] - h[1]) for c in pat)))
                c = seen.get(key, 0)
                if c >= contexts:
                    dup += 1
                    continue
                seen[key] = c + 1
                if c == 0:
                    uniq += 1
                bs = set(pat) | {c2 for c2 in ring if rng.random() < 0.5}
                byw.setdefault(w, []).append((h, bs))
        nq = 0
        for w, items in sorted(byw.items()):
            gw = g if w == (0, 0, g.W - 1, g.H - 1) else g.crop(*w, 0, name=f'{name}@{w[0]},{w[1]}')
            qs = []
            for h, bs in items:
                hl = gw.idx[(h[0] - w[0], h[1] - w[1])]
                B = gw.mask([(c[0] - w[0], c[1] - w[1]) for c in bs])
                for k in KEYLIST:
                    if gw.traps and len(gw.step(hl, B, k)) > 1:
                        for _ in range(20):       # teleport entry: 20 trials (landing distribution)
                            qs.append(trace_query(gw, J.next(), hl, B, k))
                    else:
                        qs.append(check_query(gw, J.next(), hl, B, k))
            nq += len(qs)
            J.add(name, gw, [q for q in qs if q[5] is not None], 'C', 400, 'neigh')
            J.add(name, gw, [q for q in qs if q[5] is None], 'T', 200, 'neigh-trap')
        per[name] = dict(hero_cells=len([c for c in g.cells if c not in g.traps]), dyn_cells=len(dyn),
                         windows=len(byw), unique_neighbourhoods=uniq, dedup_skipped=dup, queries=nq,
                         zone_cells_skipped=skipped)
        log('neigh', name, per[name])
    J.meta = per
    J.save()


# ============================================================================ phase: seq (exhaustive short sequences)
def all_strings(L):
    out = ['']
    for _ in range(L):
        out = [s + k for s in out for k in KEYLIST]
    return out


def crop_around(g, c, rx, ry):
    x0 = max(0, min(c[0] - rx, g.W - (2 * rx + 1)))
    y0 = max(0, min(c[1] - ry, g.H - (2 * ry + 1)))
    x1, y1 = min(g.W - 1, x0 + 2 * rx), min(g.H - 1, y0 + 2 * ry)
    return x0, y0, x1, y1


def gen_seq(names, Lsmall=4, Lbig=3):
    G = gadgets()
    J = Jobs('seq')
    per = {}
    for name in names:
        g = G[name]
        nq = nk = 0
        if g.fits():
            L = Lsmall
            for lab, B in g.inits:
                for p, c in sorted(g.ports.items()):
                    h = g.idx[c]
                    qs = []
                    for s in all_strings(L):
                        if g.traps:
                            qs.append(trace_query(g, J.next(), h, B, s))
                        else:
                            qs.append(check_query(g, J.next(), h, B, s))
                    J.add(name, g, qs, 'T' if g.traps else 'C', 512, f'seq {lab} {p}')
                    nq += len(qs)
                    nk += L * len(qs)
        else:
            L = Lbig
            for p, c in sorted(g.ports.items()):
                w = crop_around(g, c, 8, 7)
                gw = g.crop(*w, g.B0, name=f'{name}@{w[0]},{w[1]}')
                h = gw.idx[(c[0] - w[0], c[1] - w[1])]
                qs = [check_query(gw, J.next(), h, gw.B0, s) for s in all_strings(L)]
                J.add(name, gw, qs, 'C', 512, f'seq drawn {p}')
                nq += len(qs)
                nk += L * len(qs)
        per[name] = dict(L=L, starts=(len(g.inits) * len(g.ports)) if g.fits() else len(g.ports), queries=nq,
                         keys=nk)
        log('seq', name, per[name])
    J.meta = per
    J.save()


# ============================================================================ phase: walk (random + intended)
def segments(g, h, B, keys):
    """cut a deterministic full-map walk into pieces, each inside ONE window of the fixed tiling windows_for(g) with
    every hero cell of the piece >= 2 from the window's cut edges (so every cell a move reads lies in the window).
    Returns [(window, (h, B) at the piece start, keys)]."""
    tr = g.det_walk(h, B, keys)
    states = [(h, B)] + tr
    wins = windows_for(g)

    def inside(w, c):
        x0, y0, x1, y1 = w
        return ((c[0] - x0 >= 2 or x0 == 0) and (x1 - c[0] >= 2 or x1 == g.W - 1) and
                (c[1] - y0 >= 2 or y0 == 0) and (y1 - c[1] >= 2 or y1 == g.H - 1) and
                x0 <= c[0] <= x1 and y0 <= c[1] <= y1)
    out = []
    i, n = 0, len(keys)
    while i < n:
        best = None
        for w in wins:
            if not inside(w, g.cl[states[i][0]]):
                continue
            j = i
            while j < n and inside(w, g.cl[states[j + 1][0]]):
                j += 1
            if best is None or j > best[1]:
                best = (w, j)
        w, j = best
        assert j > i, ('segment stuck', g.cl[states[i][0]])
        out.append((w, states[i], keys[i:j]))
        i = j
    return out


def add_walk(J, name, g, h, B, keys, label, store):
    """queue a walk; walks on big maps are cut into window pieces (grouped per window into jobs later)."""
    if g.traps:
        store.setdefault(('T', g.name), (g, []))[1].append(trace_query(g, J.next(), h, B, keys))
        return 1
    if g.fits():
        store.setdefault(('C', g.name), (g, []))[1].append(check_query(g, J.next(), h, B, keys))
        return 1
    n = 0
    for w, (hs, Bs), ks in segments(g, h, B, keys):
        key = ('C', f'{name}@{w[0]},{w[1]}')
        if key not in store:
            store[key] = (g.crop(*w, 0, name=key[1]), [])
        gw = store[key][0]
        c = g.cl[hs]
        Bw = gw.mask([(x - w[0], y - w[1]) for x, y in g.bset(Bs) if w[0] <= x <= w[2] and w[1] <= y <= w[3]])
        store[key][1].append(check_query(gw, J.next(), gw.idx[(c[0] - w[0], c[1] - w[1])], Bw, ks))
        n += 1
    return n


def random_keys(g, h, B, n, rng, p_legal=0.8):
    ks = []
    for _ in range(n):
        legal, ill = [], []
        for k in KEYLIST:
            o = g.step(h, B, k)
            (legal if o[0] != (h, B) else ill).append((k, o))
        k, o = rng.choice(legal) if legal and (rng.random() < p_legal or not ill) else rng.choice(ill)
        ks.append(k)
        h, B = rng.choice(o)
    return ''.join(ks)


