def gen_walk(names, nrand=60, lrand=400, intended_cap=3000):
    G = gadgets()
    J = Jobs('walk')
    rng = random.Random(SEED + 7)
    per = {}
    for name in names:
        g = G[name]
        store = {}
        nr = ni = nseg = nk = 0
        # random walks: from the ports (and random floor cells) in each initial state
        starts = []
        for lab, B in g.inits:
            for p, c in sorted(g.ports.items()):
                starts.append((g.idx[c], B))
        for i in range(nrand if g.fits() else 2 * nrand):
            if g.fits():
                h, B = starts[i % len(starts)]
                if i >= len(starts) and rng.random() < 0.3:
                    free = [j for j in range(len(g.cl)) if not B >> j & 1 and g.cl[j] not in g.traps]
                    h = rng.choice(free)
            else:
                # big map: random walk in a random window (crop) from a random port or floor cell inside it
                c = rng.choice(sorted(g.ports.values())) if rng.random() < 0.5 else rng.choice(sorted(g.cells))
                if g.B0 >> g.idx[c] & 1:
                    continue
                w = crop_around(g, c, WMAX // 2 - 1, HMAX // 2)
                gw = g.crop(*w, g.B0, name=f'{name}#rw@{w[0]},{w[1]}')
                hh = gw.idx[(c[0] - w[0], c[1] - w[1])]
                ks = random_keys(gw, hh, gw.B0, lrand, rng)
                key = ('C', gw.name)
                store.setdefault(key, (gw, []))[1].append(check_query(gw, J.next(), hh, gw.B0, ks))
                nr += 1
                nk += len(ks)
                continue
            ks = random_keys(g, h, B, lrand, rng)
            add_walk(J, name, g, h, B, ks, 'random', store)
            nr += 1
            nk += len(ks)
        # intended walks
        if name == 'crossover_v2':
            for w in xover_intended():
                c = tuple(w['start'])
                nseg += add_walk(J, name, g, g.idx[c], g.B0 if ni == 0 else Bcur, w['keys'], 'intended', store)
                tr = g.det_walk(g.idx[c], g.B0 if ni == 0 else Bcur, w['keys'])
                Bcur = tr[-1][1]
                ni += 1
                nk += len(w['keys'])
        elif g.traps:
            # coin: e -> E -> T (enter, nature lands the hero on A or B), then the BFS walk from A to a (from B the
            # same keys bump walls / walk B's own corridor: every key is still compared); 40 trials each; plus the
            # walks from a, b down to the landing cells and back.
            for q in ('a',):
                ks = coin_walk(g, g.ports['e'], q)
                for _ in range(120):
                    add_walk(J, name, g, g.idx[g.ports['e']], 0, ks, 'intended', store)
                    ni += 1
                    nk += len(ks)
            for p in ('a', 'b'):
                L = g.landing[next(iter(g.traps))]['ab'.index(p)]
                ks = coin_bfs(g, g.ports[p], L) + coin_bfs(g, L, g.ports[p])
                add_walk(J, name, g, g.idx[g.ports[p]], 0, ks, 'intended', store)
                ni += 1
                nk += len(ks)
        else:
            states = g.local_states(cap=300)
            if len(states) > 300:
                states = rng.sample(states, 300)
            for B in states:
                for p in sorted(g.ports):
                    tw = g.traversal_walks(B, p)
                    items = sorted(tw.items())
                    if len(items) > 40:
                        items = rng.sample(items, 40)
                    for (q, B2), ks in items:
                        nseg += add_walk(J, name, g, g.idx[g.ports[p]], B, ks, 'intended', store)
                        ni += 1
                        nk += len(ks)
                        if ni >= intended_cap:
                            break
                    if ni >= intended_cap:
                        break
                if ni >= intended_cap:
                    break
        for (mode, _), (gg, qs) in sorted(store.items(), key=lambda kv: kv[0][1]):
            J.add(name, gg, qs, mode, 150 if mode == 'C' else 60, 'walk')
        per[name] = dict(random=nr, intended=ni, keys=nk, local_states=None if name == 'crossover_v2' or g.traps
                         else len(g.local_states(cap=300)), segments=nseg)
        log('walk', name, per[name])
    J.meta = per
    J.save()


def coin_bfs(g, a, b):
    prev = {a: None}
    dq = deque([a])
    while dq:
        x = dq.popleft()
        if x == b:
            break
        for k in KEYLIST:
            o = g.step(g.idx[x], 0, k)
            if len(o) != 1:
                continue
            y = g.cl[o[0][0]]
            if y not in prev:
                prev[y] = (x, k)
                dq.append(y)
    ks, x = [], b
    while prev[x] is not None:
        x, k = prev[x]
        ks.append(k)
    return ''.join(reversed(ks))


def coin_walk(g, c, q):
    """port c -> E (cell below T) -> T, then the BFS walk from landing A to port q."""
    T = next(iter(g.traps))
    A = g.landing[T][0]
    E = (T[0], T[1] + 1)
    return coin_bfs(g, c, E) + 'k' + coin_bfs(g, A, g.ports[q])


