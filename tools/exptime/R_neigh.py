class Gad:
    """A gadget map. cells: dict (x, y) -> '.' floor | 'T' teleport trap; boulders set; ports name -> cell;
    landing: trap -> [cells]; zone: (x0, y0, x1, y1) teleport exclude zone (map coords) or None."""

    def __init__(self, name, cells, boulders, ports, W, H, landing=None, zone=None, inits=None):
        self.name, self.W, self.H = name, W, H
        self.cells = dict(cells)
        self.traps = {c for c, t in self.cells.items() if t == 'T'}
        self.landing = landing or {}
        self.zone = zone
        self.ports = dict(ports)
        rows = []
        for y in range(H):
            rows.append(''.join(('0' if (x, y) in boulders else '.') if (x, y) in self.cells else '#'
                                for x in range(W)))
        self.board = K.Board(rows)            # A_core board (traps are floor for A_core, as in D_game)
        self.idx, self.cl = self.board.idx, self.board.cells
        self.B0 = self.board.b0
        self.inits = inits or [('drawn', self.B0)]
        self.tmask = sum(1 << self.idx[c] for c in self.traps)

    # ---------- model step: list of outcomes (h2, B2); more than one only for a teleport landing ----------
    def step(self, h, B, key):
        dx, dy = KEYS[key]
        x, y = self.cl[h]
        t = self.idx.get((x + dx, y + dy))
        if t is None:
            return [(h, B)]
        for t2, B2 in self.board.moves(h, B):
            if t2 == t:
                if B2 & self.tmask:
                    raise ValueError('boulder pushed onto a trap (design violation)')
                if self.tmask >> t2 & 1:
                    land = [self.idx[c] for c in self.landing[self.cl[t2]] if not B2 >> self.idx[c] & 1]
                    if not land:
                        raise ValueError('empty landing set')
                    return [(l, B2) for l in land]
                return [(t2, B2)]
        return [(h, B)]

    def det_walk(self, h, B, keys):
        """deterministic trajectory [(h, B)] after each key (None if a teleport is hit)."""
        tr = []
        for k in keys:
            o = self.step(h, B, k)
            if len(o) != 1:
                return None
            h, B = o[0]
            tr.append((h, B))
        return tr

    def bset(self, B):
        return [self.cl[i] for i in range(len(self.cl)) if B >> i & 1]

    def mask(self, cells):
        return sum(1 << self.idx[c] for c in cells)

    def dyn(self):
        """boulder closure (cells a boulder can ever occupy; pushes never onto traps) = D_game.Model dyn."""
        F = self.cells
        dyn = set(self.bset(self.B0)) | {c for _, B in self.inits for c in self.bset(B)}
        st = list(dyn)
        while st:
            b = st.pop()
            for dx, dy in D4:
                h, t = (b[0] - dx, b[1] - dy), (b[0] + dx, b[1] + dy)
                if h in F and h not in self.traps and t in F and t not in self.traps and t not in dyn:
                    dyn.add(t)
                    st.append(t)
        return dyn

    def crop(self, x0, y0, x1, y1, B, name=None):
        """window [x0, x1] x [y0, y1] (inclusive) -> (Gad, offset); boulders B restricted."""
        cells = {(x - x0, y - y0): t for (x, y), t in self.cells.items() if x0 <= x <= x1 and y0 <= y <= y1}
        bs = {(x - x0, y - y0) for (x, y) in self.bset(B) if x0 <= x <= x1 and y0 <= y <= y1}
        ports = {p: (c[0] - x0, c[1] - y0) for p, c in self.ports.items() if x0 <= c[0] <= x1 and y0 <= c[1] <= y1}
        assert not self.traps or (x0, y0) == (0, 0) and (x1, y1) == (self.W - 1, self.H - 1), 'never crop a coin'
        return Gad(name or f'{self.name}@{x0},{y0}', cells, bs, ports, x1 - x0 + 1, y1 - y0 + 1)

    def spec(self):
        return dict(name=self.name, W=self.W, H=self.H,
                    floor=[list(c) for c in sorted(self.cells)], traps=[list(c) for c in sorted(self.traps)],
                    zone=self.zone)

    def fits(self):
        return self.W <= WMAX and self.H <= HMAX

    # ---------- traversals (A_core semantics: start on a port, stop the first time a port is reached) ----------
    def traversal_walks(self, B, p, cap=400_000):
        pidx = {self.idx[c]: n for n, c in self.ports.items()}
        start = (self.idx[self.ports[p]], B)
        par = {start: None}
        dq = deque([start])
        out = {}
        while dq:
            s = dq.popleft()
            h, Bc = s
            for k in KEYLIST:
                o = self.step(h, Bc, k)
                if len(o) != 1:
                    continue
                s2 = o[0]
                if s2 == s or s2 in par:
                    continue
                par[s2] = (s, k)
                if s2[0] in pidx:
                    key = (pidx[s2[0]], s2[1])
                    if key not in out:
                        w, c = [], s2
                        while par[c] is not None:
                            c, kk = par[c]
                            w.append(kk)
                        out[key] = ''.join(reversed(w))
                elif len(par) < cap:
                    dq.append(s2)
        return out

    def local_states(self, cap=400):
        seen = {B for _, B in self.inits}
        dq = deque(seen)
        while dq and len(seen) < cap:
            B = dq.popleft()
            for p in self.ports:
                for (q, B2) in self.traversal_walks(B, p):
                    if B2 not in seen:
                        seen.add(B2)
                        dq.append(B2)
        return sorted(seen)


def from_rows(name, rows):
    """A_core-style rows: '#'/' ' stone, '.' floor, '0' boulder, A-Z ports (floor), a-z named floor."""
    cells, bs, ports = {}, set(), {}
    W = max(len(r) for r in rows)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in '# ':
                continue
            cells[(x, y)] = '.'
            if ch == '0':
                bs.add((x, y))
            elif ch.isupper():
                ports[ch] = (x, y)
    return Gad(name, cells, bs, ports, W, len(rows))


def tile_gad(name, T):
    cells = {c: '.' for c in T.cells}
    bs = {c for c, ch in T.cells.items() if ch == '0'}
    ports = {p: tuple(v[0]) for p, v in T.ports.items()}
    return Gad(name, cells, bs, ports, T.W, T.H)


