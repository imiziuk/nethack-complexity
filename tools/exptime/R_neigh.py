def parse_out(txt):
    import re
    st = {}
    for m in re.finditer(r'^\s*S(\d+) ([.rBNt]+)\s*$', txt, re.M):
        st[int(m.group(1))] = m.group(2)
    stline = ''.join(st[k] for k in sorted(st))
    bad = {}
    for m in re.finditer(r'^\s*X(\d+) (i=-?\d+ h=\S+ d=\S+ t=\S+)\s*$', txt, re.M):
        bad[int(m.group(1))] = m.group(2)
    yb = {}
    for m in re.finditer(r'^\s*Y(\d+)_(\d+) (\S+)\s*$', txt, re.M):
        yb.setdefault(int(m.group(1)), {})[int(m.group(2))] = m.group(3)
    for q, p in yb.items():
        if q in bad:
            bad[q] += ' b=' + ''.join(p[k] for k in sorted(p))
    trp = {}
    for m in re.finditer(r'^\s*T(\d+)_(\d+) (\S+)\s*$', txt, re.M):
        trp.setdefault(int(m.group(1)), {})[int(m.group(2))] = m.group(3)
    tr = {q: ''.join(p[k] for k in sorted(p)) for q, p in trp.items()}
    hdr = re.findall(r'^\s*H (.*)$', txt, re.M)
    asr = re.findall(r'^\s*A (\S*)\|', txt, re.M)
    return stline, bad, tr, hdr, asr


_FRESH = [True]


def run_job(args):
    """one job = one fresh game process: #wizloadlua (the only wizard-mode action), the script switches to
    playmode:normal for good (OPTIONS can be parsed once per game: duplicate_opt_detection), then the game is
    discarded (the next job starts a new one)."""
    i, job, wear = args
    src = lua_src(job, wear)
    for attempt in range(3):
        try:
            if not _FRESH[0]:
                _GAME.start()
            _FRESH[0] = False
            t0 = time.time()
            txt, dt = _GAME.run(src, timeout=900)
            stline, bad, tr, hdr, asr = parse_out(txt)
            if len(stline) != len(job['queries']):
                raise RuntimeError(f'status length {len(stline)} != {len(job["queries"])}')
            return i, dict(st=stline, bad=bad, tr=tr, hdr=hdr, asr=asr, dt=time.time() - t0)
        except Exception as e:
            err = repr(e)[-600:]
    return i, dict(error=err)


def run(phase, wear, nproc):
    import multiprocessing as mp
    root = os.path.expanduser('~/nh-witness/rneigh')
    J = json.load(open(os.path.join(OUT, f'jobs_{phase}.json')))
    jobs = J['jobs']
    resp = os.path.join(OUT, f'res_{phase}_{"wear" if wear else "nowear"}.json')
    res = {}
    if os.path.exists(resp) and '--fresh' not in sys.argv:
        res = {int(k): v for k, v in json.load(open(resp)).items() if 'error' not in v}
    only = os.environ.get('RGAD')          # optional: comma list of gadgets to run
    todo = [(i, j, wear) for i, j in enumerate(jobs) if i not in res and (not only or j['gadget'] in only.split(','))]
    log(f'run {phase} wear={wear}: {len(jobs)} jobs, {len(todo)} to do, {nproc} games')
    q = mp.Manager().Queue()
    for t in range(nproc):
        q.put(str(t))
    t0 = time.time()
    done = 0
    nq = 0
    with mp.Pool(nproc, initializer=init_worker, initargs=(q, root)) as P:
        for i, r in P.imap_unordered(run_job, todo):
            res[i] = r
            done += 1
            nq += len(jobs[i]['queries'])
            if 'error' in r:
                log(f'  job {i} ({jobs[i]["gadget"]}) ERROR {r["error"][:300]}')
            elif r['bad']:
                log(f'  job {i} ({jobs[i]["gadget"]}) {len(r["bad"])} BAD')
            if done % 50 == 0 or done == len(todo):
                log(f'  {done}/{len(todo)} jobs, {nq} queries, {nq / (time.time() - t0):.0f} q/s')
                json.dump(res, open(resp, 'w'))
    json.dump(res, open(resp, 'w'))
    log(f'run {phase} done in {time.time() - t0:.0f}s -> {resp}')


