def lua_map(spec):
    W, H = spec['W'], spec['H']
    Wm, Hm = W + 5, max(H, 6)
    g = [[' '] * Wm for _ in range(Hm)]
    for x, y in spec['floor']:
        g[y][x] = '.'
    px, py, sx, sy = W + 2, 1, W + 2, 4
    g[py][px] = '.'
    g[sy][sx] = '.'
    return '\n'.join(''.join(r) for r in g), (px, py), (sx, sy)


