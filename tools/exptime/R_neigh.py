def score_trace(g, q, trace):
    """trace-mode query on a gadget with traps: replay the model, branching on nature's landing as observed.
    Returns (ok, n_keys_compared, note, landings)."""
    qid, x, y, keys, bs, _, _, b0 = q
    h, B = g.idx[(x, y)], g.mask([tuple(c) for c in bs])
    toks = trace.split(',')
    tfin = [t for t in toks if t.startswith('T=')]
    toks = [t for t in toks if not t.startswith('T=')]
    if toks and toks[0].startswith('!b0='):
        return False, 0, 'initial boulders differ', []
    landings = []
    if len(toks) != len(keys):
        return False, 0, f'trace length {len(toks)} != {len(keys)}', landings
    curb = bstr(g.bset(B))
    for i, (k, t) in enumerate(zip(keys, toks), 1):
        parts = t.split('|')
        hx, hy = parts[0].split('r')[0].split('.')
        hc = (int(hx), int(hy))
        for p in parts[1:]:
            if p.startswith('D'):
                return False, i, f'key {i}: changed dungeon level {p}', landings
            curb = p
        outs = g.step(h, B, k)
        match = [o for o in outs if g.cl[o[0]] == hc and bstr(g.bset(o[1])) == curb]
        if len(outs) > 1:
            landings.append(hc)
        if not match:
            exp = [(g.cl[o[0]], bstr(g.bset(o[1]))) for o in outs]
            return False, i, f'key {i} {k}: real {hc} b={curb!r}, model {exp}', landings
        h, B = match[0]
    return True, len(keys), '', landings


VARIANTS = ['no_corner_rule', 'boulders_not_bad_rock', 'diag_push', 'squeeze', 'push_into_boulder',
            'one_corner_needed_both']


def wrong_step(g, h, B, key, v):
    """deliberately wrong move rules (negative controls); same interface as Gad.step on trap-free maps."""
    dx, dy = KEYS[key]
    x, y = g.cl[h]
    t = g.idx.get((x + dx, y + dy))
    if t is None:
        return (h, B)
    diag = dx and dy
    if B >> t & 1 and (not diag or v == 'diag_push'):
        b = g.idx.get((x + 2 * dx, y + 2 * dy))
        if b is None or B >> b & 1:
            if v == 'squeeze':
                return (t, B)
            if v == 'push_into_boulder' and b is not None:
                return (t, B & ~(1 << t))
            return (h, B)
        return (t, (B & ~(1 << t)) | (1 << b))
    if B >> t & 1:
        return (h, B)
    if diag and v != 'no_corner_rule':
        cs = [g.idx.get(c) for c in ((x + dx, y), (x, y + dy))]
        good = [i is not None and (v == 'boulders_not_bad_rock' or not B >> i & 1) for i in cs]
        if not (all(good) if v == 'one_corner_needed_both' else any(good)):
            return (h, B)
    return (t, B)


def controls():
    """for every passing deterministic query (real == A_core after every key): count the queries on which a wrong
    rule would have predicted a different trajectory, i.e. would have been caught by the real game; also count the
    outcome classes of all compared keys."""
    G = gadgets()
    cnt = {v: 0 for v in VARIANTS}
    cls = {}
    n = 0
    for phase in ('neigh', 'seq', 'walk'):
        jp = os.path.join(OUT, f'jobs_{phase}.json')
        rp = os.path.join(OUT, f'res_{phase}_wear.json')
        if not (os.path.exists(jp) and os.path.exists(rp)):
            continue
        J = json.load(open(jp))
        R = {int(k): v for k, v in json.load(open(rp)).items()}
        cache = {}
        for i, job in enumerate(J['jobs']):
            r = R.get(i)
            if job['mode'] != 'C' or r is None or 'error' in r:
                continue
            sp = job['spec']
            gw = cache.get(sp['name'])
            if gw is None:
                gw = Gad(sp['name'], {tuple(c): '.' for c in sp['floor']}, set(), {}, sp['W'], sp['H'])
                cache[sp['name']] = gw
            for q, s in zip(job['queries'], r['st']):
                if s not in '.r':
                    continue
                n += 1
                h0, B0 = gw.idx[(q[1], q[2])], gw.mask([tuple(c) for c in q[4]])
                for v in VARIANTS:
                    h, B = h0, B0
                    hh, BB = h0, B0
                    for k in q[3]:
                        h, B = gw.step(h, B, k)[0]
                        hh, BB = wrong_step(gw, hh, BB, k, v)
                        if (h, B) != (hh, BB):
                            cnt[v] += 1
                            break
                        # wrong model agrees so far; continue from the (shared) true state
                h, B = h0, B0
                for k in q[3]:
                    h2, B2 = gw.step(h, B, k)[0]
                    dx, dy = KEYS[k]
                    x, y = gw.cl[h]
                    tc = (x + dx, y + dy)
                    if B2 != B:
                        c = 'push'
                    elif h2 != h:
                        c = 'step_diag' if dx and dy else 'step'
                    elif tc not in gw.idx:
                        c = 'refused_stone'
                    elif B >> gw.idx[tc] & 1:
                        c = 'refused_boulder'
                    else:
                        c = 'refused_corner'
                    cls[c] = cls.get(c, 0) + 1
                    h, B = h2, B2
    json.dump(dict(passing_queries=n, variant_caught=cnt, key_classes=cls),
              open(os.path.join(OUT, 'controls.json'), 'w'), indent=1)
    print('passing deterministic queries', n)
    print('| wrong rule | queries where the real game disagrees with it |')
    print('|---|---|')
    for v in VARIANTS:
        print(f'| {v} | {cnt[v]} |')
    print('key classes', dict(sorted(cls.items())))


def report():
    G = gadgets()
    summ = {}
    rows = []
    mism = []
    for phase in ('neigh', 'seq', 'walk'):
        jp = os.path.join(OUT, f'jobs_{phase}.json')
        if not os.path.exists(jp):
            continue
        J = json.load(open(jp))
        for wear in ('wear', 'nowear'):
            rp = os.path.join(OUT, f'res_{phase}_{wear}.json')
            if not os.path.exists(rp):
                continue
            R = {int(k): v for k, v in json.load(open(rp)).items()}
            agg = {}
            for i, job in enumerate(J['jobs']):
                r = R.get(i)
                if r is None and wear == 'nowear':
                    continue                  # control runs cover only some gadgets (RGAD)
                a = agg.setdefault(job['gadget'], dict(queries=0, keys=0, ok=0, bad=0, nobuild=0, missing=0,
                                                       retried=0, landings={}, hdr_bad=0, assert_fail=0,
                                                       escapes=0))
                if r is None or 'error' in r:
                    a['missing'] += len(job['queries'])
                    continue
                for h in r['hdr']:
                    if 'pm=normal pm_now=normal stair_in_pocket=true' not in h:
                        a['hdr_bad'] += 1
                a['assert_fail'] += sum(len(x) for x in r['asr'])
                gname = job['gadget']
                gw = None
                for q, s in zip(job['queries'], r['st']):
                    a['queries'] += 1
                    if s == 'N':
                        a['nobuild'] += 1
                        continue
                    if s in '.r':
                        a['ok'] += 1
                        a['keys'] += len(q[3])
                        a['retried'] += s == 'r'
                    elif s == 'B':
                        a['bad'] += 1
                        info = r['bad'].get(str(q[0]), r['bad'].get(q[0], '?'))
                        fi = int(info.split()[0][2:]) if info != '?' else 0
                        a['keys'] += max(fi, 0)
                        mism.append(dict(phase=phase, wear=wear, gadget=gname, window=job['spec']['name'],
                                         start=[q[1], q[2]], keys=q[3], boulders=q[4], real=info,
                                         model_hero=q[5][2 * fi - 2:2 * fi] if fi > 0 else None,
                                         model_b=None))
                    elif s == 't':
                        if gw is None:
                            gw = G[gname] if job['spec']['name'] == gname else None
                        ok, nk, note, land = score_trace(gw, q, r['tr'].get(str(q[0]), r['tr'].get(q[0], '')))
                        a['keys'] += nk
                        for c in land:
                            a['landings'][str(c)] = a['landings'].get(str(c), 0) + 1
                        if ok:
                            a['ok'] += 1
                        else:
                            a['bad'] += 1
                            a['escapes'] += 'model' in note and str(tuple(next(iter(gw.traps)))) in note
                            mism.append(dict(phase=phase, wear=wear, gadget=gname, window=job['spec']['name'],
                                             start=[q[1], q[2]], keys=q[3], boulders=q[4], real=note))
            for gname, a in agg.items():
                summ[f'{phase}/{wear}/{gname}'] = a
                rows.append((phase, wear, gname, a))
    json.dump(dict(summary=summ, mismatches=mism[:2000], n_mismatches=len(mism)),
              open(os.path.join(OUT, 'summary.json'), 'w'), indent=1)
    print('| phase | boots | gadget | queries | keys compared | ok | mismatches | nobuild | missing | fumble retries |')
    print('|---|---|---|---|---|---|---|---|---|---|')
    tot = dict(queries=0, keys=0, bad=0, nobuild=0, missing=0)
    for phase, wear, gname, a in rows:
        print(f"| {phase} | {wear} | {gname} | {a['queries']} | {a['keys']} | {a['ok']} | {a['bad']} | "
              f"{a['nobuild']} | {a['missing']} | {a['retried']} |" + (f" landings {a['landings']}" if a['landings']
                                                                         else '')
              + (f" HDR_BAD {a['hdr_bad']}" if a['hdr_bad'] else '') + (f" ASSERT {a['assert_fail']}"
                                                                         if a['assert_fail'] else ''))
        for k in tot:
            tot[k] += a[k]
    print('TOTAL', tot)
    print(f'{len(mism)} mismatches')
    for m in mism[:30]:
        print(' ', m)


