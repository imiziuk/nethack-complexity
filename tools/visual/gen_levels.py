"""Write the Lua levels for the visual demo (tools/visual/levels/*.lua).

Each level follows the L_OFF instance shape of proofs/phase2-spec.md / proofs/hu-off.md B.2:
mongen=false, hunger=false, noflip + sokoban flags, solidfill, explicit des.map at (1,0), boulders, optional
sealed sentinel pit, one-cell teleport region for the hero, finalize, then the hero holds only a cursed loadstone.
Unlike the witnesses, the script does NOT press keys: the keys are typed into the real tty by capture.py.
The retry loop and the stair-to-floor fix are the witnesses' harness (setup randomness only, see off_push_orth.lua).

Board text: '-'/'|' wall, '.' floor, 'B' boulder on floor, '@' hero start (floor), 'g'/'a'/'b' floor (labels are
drawn by render.py, the game only sees floor), 'P' sentinel pit cell (floor + pit, sealed by walls),
'S' (added automatically) sealed pocket that receives the DL1 branch stair.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

LEVELS = {
    # scene A1: orthogonal push, push into a wall, m-prefix
    'a1_push': """
---------
|.@B....|
---------""",
    # scene A2: diagonal push refused
    'a2_diag': """
-------
|.....|
|..B..|
|.@...|
-------""",
    # scene A3: no squeezing diagonally between two boulders
    'a3_squeeze': """
-------
|.....|
|.B...|
|.@B..|
-------""",
    # scene B: order matters (found and checked with push1f.py / find_puzzle.py); sentinel pit as in f(I)
    'b_puzzle': """
----------
--...B.---
-@...Bg-P-
-..--.----
----------""",
    # scene C: self-closing one-way door (found with find_oneway.py)
    'c_oneway': """
--------
--B-.---
-aBbB-P-
--...---
--------""",
}

START = {'c_oneway': 'a'}   # hero start label when it is not '@'

TEMPLATE = """-- {name}.lua -- generated by tools/visual/gen_levels.py (visual demo level, keys are typed by capture.py)
nh.debug_flags({{ mongen = false, hunger = false }});
local OX, OY = 1, 0;
for attempt = 1, 10 do
   des.reset_level();
   des.level_flags("noflip", "sokoban", "noteleport", "hardfloor", "solidify", "premapped");
   des.level_init({{ style = "solidfill", fg = " ", lit = true }});
   des.map({{ x = OX, y = OY, map = [[
{map}]] }});
   des.region(selection.area(0, 0, {w1}, {h1}), "lit");   -- light the board so the whole puzzle is in view
{objects}   des.teleport_region({{ region = {{ {sx} + OX, {sy} + OY, {sx} + OX, {sy} + OY }}, region_islev = true, dir = "both" }});
   des.finalize_level();
   for _, v in pairs(nh.stairways()) do
      des.terrain(v.x, v.y, ".");  -- DL1 branch stair from finalize (as in the witnesses)
   end
   u.clear_inventory();
   u.giveobj(obj.new("cursed loadstone"));
   if (u.ux == {sx} + OX and u.uy == {sy} + OY) then break; end
end
"""


def add_branch_pocket(rows):
    """Append a sealed 1-cell pocket 'S' (8 wall neighbours, >= 3 columns from any board cell) on row 1.
    The DL1 branch stair that finalize must place is declared there (des.levregion type=branch, review-3),
    so it can never land on the hero's start cell."""
    pad = {0: '---', 1: '-S-', 2: '---'}
    return [r + pad.get(y, '   ') for y, r in enumerate(rows)]


def build(name, board):
    rows = add_branch_pocket(board.strip('\n').split('\n'))
    start_ch = START.get(name, '@')
    objs, mrows, sx, sy = [], [], None, None
    for y, r in enumerate(rows):
        m = ''
        for x, c in enumerate(r):
            if c == 'B':
                objs.append(f'   des.object("boulder", {x}, {y});\n')
            if c == 'P':
                objs.append(f'   des.trap("pit", {x}, {y});   -- sealed sentinel pit (keeps the Sokoban flag)\n')
            if c == 'S':
                px, py = x, y
            if c == start_ch:
                sx, sy = x, y
            m += c if c in '-| ' else '.'
        mrows.append(m)
    objs.append(f'   des.levregion({{ region = {{ {px} + OX, {py} + OY, {px} + OX, {py} + OY }}, region_islev = true, '
                f'type = "branch" }});   -- branch stair goes into the sealed pocket\n')
    return TEMPLATE.format(name=name, map='\n'.join(mrows), objects=''.join(objs), sx=sx, sy=sy,
                           w1=max(len(r) for r in mrows) - 1, h1=len(mrows) - 1)


if __name__ == '__main__':
    os.makedirs(os.path.join(HERE, 'levels'), exist_ok=True)
    for name, board in LEVELS.items():
        with open(os.path.join(HERE, 'levels', name + '.lua'), 'w', newline='\n') as f:
            f.write(build(name, board))
        with open(os.path.join(HERE, 'levels', name + '.txt'), 'w', newline='\n') as f:
            f.write(board.strip('\n') + '\n')
    print('wrote', len(LEVELS), 'levels')
